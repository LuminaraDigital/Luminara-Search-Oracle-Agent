export const FREE_AI_ANSWER_LABEL = 'AI search answer (generated by Luminara from live web results)';

const PLACE = /^[\p{L}][\p{L}\s'.-]{1,39}$/u;

export function cleanPlace(value: unknown): string {
  if (typeof value !== 'string') return '';
  const trimmed = value.trim().replace(/\s+/g, ' ');
  return PLACE.test(trimmed) ? trimmed : '';
}

export function questionFor(suburb: string, state: string): string {
  return `Who is the best real estate agent/agency in ${suburb}, ${state}?`;
}

export function cacheUrl(suburb: string, state: string): string {
  const slug = (value: string) => encodeURIComponent(value.toLowerCase());
  return `https://luminara-cache.internal/free-answer/${slug(suburb)}/${slug(state)}`;
}

/** Names the model listed that also appear in the source text. */
export function agenciesFromAnswer(answer: string, sourceText: string): string[] {
  const line = answer.split('\n').find((row) => /^AGENCIES:/i.test(row.trim()));
  if (!line) return [];
  const blob = sourceText.toLowerCase();
  const seen = new Set<string>();
  const out: string[] = [];
  for (const part of line.replace(/^AGENCIES:\s*/i, '').split(';')) {
    const name = part.trim();
    const key = name.toLowerCase();
    if (name.length < 2 || name.length > 80 || key === 'none' || key === 'unknown') continue;
    if (seen.has(key) || !blob.includes(key)) continue;
    seen.add(key);
    out.push(name);
    if (out.length === 8) break;
  }
  return out;
}

export function userIsNamed(answer: string, brand: string): boolean {
  const name = brand.trim().toLowerCase();
  return name.length >= 2 && answer.toLowerCase().includes(name);
}

export function realEstateAgentFix(brand: string, suburb: string, state: string): string {
  return JSON.stringify({
    '@context': 'https://schema.org',
    '@type': 'RealEstateAgent',
    name: brand.trim() || 'Your agency',
    areaServed: {
      '@type': 'City',
      name: suburb,
      address: { '@type': 'PostalAddress', addressRegion: state, addressCountry: 'AU' },
    },
  }, null, 2);
}

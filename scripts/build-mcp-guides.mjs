#!/usr/bin/env node
/**
 * Compiles plugins/luminara/skills/<name>/SKILL.md into worker/mcpGuides.generated.ts, which the
 * get_guide MCP tool serves. A host with no Luminara plugin installed gets the same workflows,
 * and always the version the server it is talking to was built with.
 *
 * Run: node scripts/build-mcp-guides.mjs   (also runs in `prebuild` and `pretest`)
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const skillsDir = join(root, 'plugins', 'luminara', 'skills');
const outFile = join(root, 'worker', 'mcpGuides.generated.ts');

function parseSkill(dir) {
  const md = readFileSync(join(skillsDir, dir, 'SKILL.md'), 'utf8').replace(/\r\n/g, '\n');
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(md);
  if (!match) throw new Error(`${dir}/SKILL.md has no frontmatter`);
  const field = (key) => new RegExp(`^${key}:\\s*(.+)$`, 'm').exec(match[1])?.[1].trim();
  const topic = field('name');
  const description = field('description');
  if (topic !== dir) throw new Error(`${dir}/SKILL.md: name must equal its folder name`);
  if (!description) throw new Error(`${dir}/SKILL.md: description is required`);
  return { topic, description, body: match[2].trim() };
}

const guides = readdirSync(skillsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()
  .map(parseSkill);

writeFileSync(
  outFile,
  [
    '// Generated by scripts/build-mcp-guides.mjs from plugins/luminara/skills. Do not edit by hand.',
    'export type McpGuide = { topic: string; description: string; body: string };',
    '',
    `export const MCP_GUIDES: readonly McpGuide[] = ${JSON.stringify(guides, null, 2)};`,
    '',
  ].join('\n'),
);
console.log(`mcp guides: ${guides.length} written`);

/**
 * Privacy and Terms. The words match the Worker HTML. Not legal advice.
 */
export const LegalPage: React.FC<Props> = ({ kind, onBack }) => {
  const isPrivacy = kind === 'privacy';
  const updated = isPrivacy ? PRIVACY_UPDATED : TERMS_UPDATED;

  useEffect(() => {
    return bindTelegramBackButton(onBack);
  }, [onBack]);

  const body = isPrivacy ? <PrivacyBody /> : <TermsBody />;
  const meta = `Luminara Suite · Operated by ${OPERATOR_LINE} · Last updated ${updated}`;

  if (isInTelegram()) {
    return (
      <main id="main" tabIndex={-1} className="min-h-screen bg-black px-6 py-12 text-[var(--color-ink-2)] outline-none">
        <div className="mx-auto max-w-2xl">
          <button type="button" onClick={onBack} className="mb-8 text-sm text-[var(--gold-light)]">
            Back
          </button>
          <h1 className="font-serif text-4xl text-[var(--color-ink)]">{isPrivacy ? 'Privacy policy' : 'Terms of Service'}</h1>
          <p className="mt-3 text-sm">{meta}</p>
          {body}
        </div>
      </main>
    );
  }

  return (
    <MarketingChromeContext.Provider value={DOCUMENT_CHROME}>
      <MarketingPageShell>
        <MarketingPageHeader
          eyebrow={isPrivacy ? 'Privacy' : 'Terms'}
          title={
            <>
              {isPrivacy ? 'Privacy' : 'Terms of'} <span className="italic lx-gold-text pr-[0.08em]">{isPrivacy ? 'policy.' : 'Service.'}</span>
            </>
          }
          lede={meta}
        />
        {body}
      </MarketingPageShell>
    </MarketingChromeContext.Provider>
  );
};
